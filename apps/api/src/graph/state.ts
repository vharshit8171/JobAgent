import { Annotation, MessagesAnnotation } from '@langchain/langgraph';
import type { MatchReport, ParsedJob, Tailoring } from './schemas.js';

// 1. Create a reusable state field with an initial value and a "last write wins" update strategy.
export function field<T>(initial: T) {
  return Annotation<T>({
    reducer: (_old, next) => next, // Replace the previous value with the latest update.
    default: () => initial, // Provide the initial value when the graph starts.
  });
}

// 2. Define the complete shared state used by different LangGraph nodes.
export const AnalysisState = Annotation.Root({
  userId: field(''), // Stores the ID of the user whose resume is being analyzed.
  jobDescription: field(''), // Stores the job description provided for analysis.
  parsedJob: field<ParsedJob | null>(null), // Stores the extracted and structured job details.
  evidence: field<Record<string, string[]>>({}), // Stores retrieved resume evidence mapped to job requirements.
  matchReport: field<MatchReport | null>(null), // Stores the candidate's job compatibility report.
  score: field(0), // Stores the calculated job matching score.
  draft: field<Tailoring | null>(null), // Stores the tailored resume bullets and cover letter.
  groundingIssues: field<string[]>([]), // Stores claims that are not supported by candidate information.
  attempts: field(0), // Tracks the number of review or correction attempts.
  reviewApproved: field<boolean | null>(null), // Stores whether the generated result has passed review.
  outcome: field<'saved' | 'low_fit' | 'discarded' | null>(null), // Stores the final result of the job analysis workflow.
});

// 3. Export State and Update types for accessing and modifying graph state.
export type State = typeof AnalysisState.State;
export type Update = typeof AnalysisState.Update;

/** 4. Combine all unique evidence chunks into a single text block. */
export function collectEvidence(evidence: Record<string, string[]>): string {
  return [...new Set(Object.values(evidence).flat())].join('\n---\n');
}

/** The main graph's state: chat messages + everything the analysis workflow needs. */
export const MainState = Annotation.Root({
  ...MessagesAnnotation.spec,
  ...AnalysisState.spec,
  intent: field<'analyze_job' | 'chat'>('chat'),
});

export type MainStateType = typeof MainState.State;
export type MainUpdate = typeof MainState.Update;

/**
 * State survives between messages in a thread. Without this reset, a second job
 * analysis would start with the first one's retry count and old draft.
 */
export const resetAnalysis: Update = {
  parsedJob: null,
  evidence: {},
  matchReport: null,
  score: 0,
  draft: null,
  groundingIssues: [],
  attempts: 0,
  reviewApproved: null,
  outcome: null,
};


